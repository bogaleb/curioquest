export const pageById = new Map(colouringPages.map((page) => [page.id, page]));

/** The pages a child of this tier is offered, in shelf order. */
export function pagesForTier(tier: StudioTier): ColouringPage[] {
  return colouringPages.filter((page) => page.tiers.includes(tier));
}

/** A page's fillable regions — everything that is not a detail line. */
export function fillablePieces(page: ColouringPage): Piece[] {
  return page.pieces.filter((piece) => !piece.detail);
}
