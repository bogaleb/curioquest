import type { ByTier, ColouringPage, Piece, PieceShape, StudioTier } from "./types";

/**
 * The colouring book.
 *
 * Twenty-four pages, every one a list of named, fillable parts rather than an outline.
 * That is the whole difference between this and what it replaces: the old pages were
 * `ctx.stroke()` calls, so "colouring in" meant dragging a brush and trying not to go
 * over the line, which is a fine motor exercise rather than a colouring book. Here a
 * child taps the cat's ear and the ear fills, named out loud, instantly.
 *
 * Three authoring rules:
 *
 * **Every part is a word.** `name` is read aloud and is the region's accessible name, so
 * a page is also a vocabulary walk: ear, whisker, paw, tail, petal, stem, chimney, sail,
 * fin, wing. A part called "shape 4" would be a wasted opportunity and unusable by a
 * child who is listening rather than looking.
 *
 * **The starting tones are a picture, not an answer.** A page opens tinted so it reads as
 * a cat rather than as a wireframe, and the first tap overwrites. Nothing anywhere scores
 * a child against them; a purple cat is a correct cat.
 *
 * **Order is paint order.** Pieces are drawn in array order, so the background goes
 * first and the eyes go last. `detail: true` marks a part that is drawn on top and never
 * filled — a pupil, a whisker, a mouth — and a tap on one fills whatever is underneath,
 * which is what a child aiming at a face actually means.
 */

/** Terse constructor, because a page is thirty of these and readability is the list. */
function pc(
  id: string,
  shape: PieceShape,
  x: number,
  y: number,
  w: number,
  h: number,
  tone: string,
  name: string,
  extra: Partial<Piece> = {},
): Piece {
  return { id, shape, x, y, w, h, tone, name, ...extra };
}

/** A detail line: drawn on top, never filled. */
const dt = (extra: Partial<Piece> = {}): Partial<Piece> => ({ detail: true, ...extra });

const t3 = <T,>(explorer: T, investigator: T, scientist: T): ByTier<T> => ({
  explorer, investigator, scientist,
});

const ALL: StudioTier[] = ["explorer", "investigator", "scientist"];
const OLDER: StudioTier[] = ["investigator", "scientist"];

/** A pair of eyes with pupils, used by every face on the shelf. */
function face(cx: number, cy: number, spread: number, size: number): Piece[] {
  return [
    pc("eye-left", "eye", cx - spread, cy, size, size * 1.2, "paper", "an eye"),
    pc("eye-right", "eye", cx + spread, cy, size, size * 1.2, "paper", "the other eye"),
    pc("pupil-left", "pupil", cx - spread, cy + size * 0.1, size * 0.45, size * 0.45, "ink", "an eye", dt()),
    pc("pupil-right", "pupil", cx + spread, cy + size * 0.1, size * 0.45, size * 0.45, "ink", "an eye", dt()),
  ];
}

